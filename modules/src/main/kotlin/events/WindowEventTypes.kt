package events

// ============================================================================
// ======================= WindowEvent ========================================
// ============================================================================

interface WindowEvent {

}

// ============================================================================
// ======================= WindowMoveEvent ====================================
// ============================================================================

data class WindowMoveEvent(val posX: Int, val posY: Int) : WindowEvent {}

